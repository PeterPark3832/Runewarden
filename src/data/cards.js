export const CARD_DEFS = [...BASE_CARD_DEFS, ...SHADOW_CARDS, ...SOLAR_CARDS, ...STORM_CARDS];

/**
 * DLC 소유 여부로 필터링된 카드풀 반환.
 * 상점·노드 등 런타임 카드 선택에 사용.
 */
export function getCardPool() {
  return [
    ...BASE_CARD_DEFS,
    ...(hasDLC('shadow_realm')   ? SHADOW_CARDS : []),
    ...(hasDLC('solar_dominion') ? SOLAR_CARDS  : []),
    ...(hasDLC('storm_imperium') ? STORM_CARDS  : []),
  ];
}

// 시작 덱 (14장) — v0.3: 타워 6 + 강화 4 + 주문 4
export function buildStarterDeck() {
  const picks = [
    // 타워 6장
    'summon_archer', 'summon_archer', 'summon_archer', 'summon_archer',
    'summon_cannon', 'summon_cannon',
    // 강화 4장
    'aug_sharpen', 'aug_sharpen',
    'aug_extend',
    'aug_haste',
    // 주문 4장
    'spell_gold', 'spell_gold',
    'spell_fireball',
    'spell_freeze',
  ];
  return picks.map(id => ({ ...CARD_DEFS.find(c => c.id === id), uid: Math.random() }));
}
